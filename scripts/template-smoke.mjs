import { chromium } from 'playwright-core';
import { createDiagram } from './dialog-test-helper.mjs';

const browser = await chromium.launch({ executablePath:'/usr/bin/google-chrome', headless:true, args:['--no-sandbox'] });
const context = await browser.newContext({ acceptDownloads:true, viewport:{width:1350,height:850} });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const assert = (condition, message) => { if (!condition) throw new Error(message); };
async function gallery() {
  await page.locator('#new-document').click();
  await page.locator('dialog.catalog-dialog[open]').waitFor();
  await page.locator('#mode-templates').click();
  await page.locator('.template-gallery').waitFor();
}
try {
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173/');
  await page.locator('.welcome').waitFor();
  await gallery();
  assert(await page.locator('.template-card').count() === 19, 'built-in inventory incomplete');
  await page.locator('#template-search').fill('approval');
  await page.locator('[data-template-id="bpmn-approval"]').click();
  await page.locator('#template-full-preview svg').waitFor();
  assert((await page.locator('#template-full-preview').innerHTML()).includes('Review request'), 'preview does not represent source');
  await page.locator('#template-diagram-name').fill('Gallery Approval');
  await page.locator('.catalog-dialog .studio-dialog-submit').click();
  await page.locator('.doc-tab.active').filter({hasText:'Gallery Approval'}).waitFor();
  await page.locator('#native-canvas .djs-container').waitFor({timeout:30000});
  await page.locator('#native-canvas [data-element-id="Task_Review"]').click({force:true});
  await page.locator('#bpmn-name').fill('Edited approval');
  await page.locator('#bpmn-name').dispatchEvent('change');
  await page.waitForTimeout(500);
  await page.locator('#save-template').click();
  const saveDialog = page.locator('dialog.studio-dialog[open]');
  await saveDialog.waitFor();
  await saveDialog.locator('[name="name"]').fill('My Approval');
  await saveDialog.locator('[name="description"]').fill('My editable approval workflow');
  await page.evaluate(() => {
    window.originalTemplatePut = IDBObjectStore.prototype.put;
    IDBObjectStore.prototype.put = function(...args) { if (this.name === 'templates') throw new Error('Template quota test'); return window.originalTemplatePut.apply(this, args); };
  });
  await saveDialog.locator('.studio-dialog-submit').click();
  await saveDialog.locator('.studio-dialog-error:not([hidden])').waitFor();
  if ((await saveDialog.locator('[name="name"]').inputValue()) !== 'My Approval') throw new Error('Storage failure lost template form state');
  await page.evaluate(() => { IDBObjectStore.prototype.put = window.originalTemplatePut; delete window.originalTemplatePut; });
  await saveDialog.locator('.studio-dialog-submit').click();
  await saveDialog.waitFor({state:'detached'});
  await gallery();
  await page.locator('#template-source').selectOption('custom');
  await page.locator('.template-card[data-template-id^="user-"]').first().click();
  assert(await page.locator('#template-detail').getByText('My Approval').count() > 0, 'custom template missing');
  await page.locator('#template-edit').click();
  await page.locator('#template-edit-form [name="title"]').fill('Renamed Approval');
  await page.locator('#template-edit-save').click();
  await page.locator('#template-detail').getByText('Renamed Approval').waitFor();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#template-export').click();
  const download = await downloadPromise;
  assert(download.suggestedFilename().endsWith('.astpl'), 'template export missing');
  const exportPath = await download.path();
  await page.locator('#template-duplicate').click();
  await page.waitForFunction(() => document.querySelectorAll('.template-card').length === 2);
  await page.locator('#template-delete').click();
  await page.locator('#template-delete').click();
  await page.waitForFunction(() => document.querySelectorAll('.template-card').length === 1);
  await page.locator('#template-file').setInputFiles(exportPath);
  await page.waitForFunction(() => document.querySelectorAll('.template-card').length === 2);
  await page.locator('#template-file').setInputFiles(exportPath);
  await page.locator('.template-import-choice').waitFor();
  await page.locator('#template-conflict').selectOption('copy');
  await page.locator('#template-import-confirm').click();
  await page.waitForFunction(() => document.querySelectorAll('.template-card').length === 3);
  await page.locator('#template-file').setInputFiles(exportPath);
  await page.locator('.template-import-choice').waitFor();
  await page.locator('#template-conflict').selectOption('skip');
  await page.locator('#template-import-confirm').click();
  await page.locator('.template-import-choice').waitFor({state:'detached'});
  assert(await page.locator('.template-card').count() === 3, 'skip conflict created another template');
  await page.locator('#template-file').setInputFiles(exportPath);
  await page.locator('.template-import-choice').waitFor();
  await page.locator('#template-conflict').selectOption('replace');
  await page.locator('#template-import-confirm').click();
  await page.locator('.template-import-choice').waitFor({state:'detached'});
  await page.waitForFunction(() => document.querySelectorAll('.template-card').length === 3);
  await page.locator('.template-card').first().click();
  await page.locator('#template-diagram-name').fill('Approval From Template');
  await page.locator('.catalog-dialog .studio-dialog-submit').click();
  await page.locator('.doc-tab.active').filter({hasText:'Approval From Template'}).waitFor();
  await page.locator('#native-canvas .djs-container').waitFor({timeout:30000});
  await page.reload();
  await page.locator('.doc-tab.active').filter({hasText:'Approval From Template'}).waitFor();
  await gallery();
  await page.locator('#mode-blank').click();
  await page.locator('[data-catalog-id="sequence"]').click();
  await page.locator('#catalog-name').fill('Blank still works');
  await page.locator('.catalog-dialog .studio-dialog-submit').click();
  await page.locator('.doc-tab.active').filter({hasText:'Blank still works'}).waitFor();
  assert(!errors.length, `browser errors: ${errors.join('; ')}`);
  console.log('Template smoke passed: built-in preview/create/edit, save/manage/export/import, reload, blank workflow');
} finally { await browser.close(); }
